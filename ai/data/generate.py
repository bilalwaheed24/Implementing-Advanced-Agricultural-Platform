def hazard_derived_sequence(hazard_sequence: str, divergence: float = 0.06,
                            seed: int = 5) -> str:
    """A mutated descendant of a hazard sequence — the case exact matching would miss."""
    rng = random.Random(seed)
    bases = list(hazard_sequence)
    for i in range(len(bases)):
        if rng.random() < divergence:
            bases[i] = rng.choice([b for b in "ACGT" if b != bases[i]])
    return "".join(bases)


