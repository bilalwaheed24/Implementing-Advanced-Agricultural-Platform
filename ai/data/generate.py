def fraud_feature_rows(count: int = 600, seed: int = 21) -> np.ndarray:
    """Feature rows for the novelty model: mostly clean chains, as in reality."""
    rng = random.Random(seed)
    rows = []
    for _ in range(count):
        events = rng.randint(4, 9)
        rows.append([
            float(events), float(rng.uniform(200, 20000)), float(rng.randint(0, 3)),
            float(rng.randint(0, 2)), 0.0, 0.0,
            float(rng.uniform(1.0, 6.0)), float(rng.uniform(-1.0, 3.0)),
        ])
    return np.array(rows, dtype=float)


def write_json(path: str | Path, name: str, seed: int, payload: Any) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps({"provenance": provenance(name, seed), "data": payload},
                                 indent=2))
    return target
