CROP_CLASSES = ["HEALTHY", "LEAF_BLIGHT", "RUST", "NUTRIENT_DEFICIENCY"]


def leaf_patch(label: str, size: int = 48, rng: np.random.Generator | None = None) -> np.ndarray:
    """Procedurally generate an RGB leaf patch with class-characteristic texture."""
    rng = rng or np.random.default_rng(0)
    yy, xx = np.mgrid[0:size, 0:size] / size
    base = np.zeros((size, size, 3), dtype=np.float32)
    # Healthy leaf ground: green dominant with a vein gradient.
    base[..., 1] = 0.55 + 0.15 * np.sin(yy * 6) + rng.normal(0, 0.03, (size, size))
    base[..., 0] = 0.22 + 0.05 * xx + rng.normal(0, 0.03, (size, size))
    base[..., 2] = 0.18 + rng.normal(0, 0.03, (size, size))

    if label == "LEAF_BLIGHT":
        for _ in range(rng.integers(3, 7)):
            cy, cx = rng.uniform(0.15, 0.85, 2)
            radius = rng.uniform(0.08, 0.20)
            mask = ((yy - cy) ** 2 + (xx - cx) ** 2) < radius ** 2
            base[mask] = base[mask] * 0.35 + np.array([0.42, 0.32, 0.12], dtype=np.float32) * 0.65
    elif label == "RUST":
        for _ in range(rng.integers(25, 70)):
            cy, cx = rng.uniform(0.05, 0.95, 2)
            radius = rng.uniform(0.012, 0.032)
            mask = ((yy - cy) ** 2 + (xx - cx) ** 2) < radius ** 2
            base[mask] = np.array([0.62, 0.28, 0.08], dtype=np.float32)
    elif label == "NUTRIENT_DEFICIENCY":
        # Interveinal chlorosis: yellowing that spares the veins.
        chlorosis = (np.sin(yy * 22) ** 2) * rng.uniform(0.5, 0.9)
        base[..., 0] += 0.38 * chlorosis
        base[..., 1] += 0.22 * chlorosis
        base[..., 2] -= 0.06 * chlorosis

    return np.clip(base, 0.0, 1.0).astype(np.float32)


def crop_image_dataset(per_class: int = 180, size: int = 48, seed: int = 11):
    rng = np.random.default_rng(seed)
    images, labels = [], []
    for index, label in enumerate(CROP_CLASSES):
        for _ in range(per_class):
            images.append(leaf_patch(label, size, rng))
            labels.append(index)
    images_array = np.stack(images)
    labels_array = np.array(labels, dtype=np.int64)
    order = rng.permutation(len(labels_array))
    return images_array[order], labels_array[order]


