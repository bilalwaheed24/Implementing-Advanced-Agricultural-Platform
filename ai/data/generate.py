def provenance(name: str, seed: int, **extra: Any) -> dict[str, Any]:
    return {
        "dataset": name,
        "marking": DATA_MARKING,
        "generator": GENERATOR,
        "seed": seed,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        **extra,
    }


