def _diurnal(hour: float, low: float, high: float, peak_hour: float = 14.0) -> float:
    mid, amplitude = (low + high) / 2, (high - low) / 2
    return mid + amplitude * math.sin((hour - peak_hour + 6) / 24 * 2 * math.pi)


def telemetry_reading(device_type: str, when: datetime, rng: random.Random,
                      drift: float = 0.0) -> dict[str, float]:
    """One physically plausible reading for a device class at a point in time."""
    hour = when.hour + when.minute / 60
    day_of_year = when.timetuple().tm_yday
    season = math.sin((day_of_year - 80) / 365 * 2 * math.pi)      # +1 midsummer

    if device_type == "SOIL_SENSOR":
        return {
            "soil_moisture_pct": round(max(0.0, min(100.0, 28 + 8 * season * -0.4
                                                    + rng.gauss(0, 2.5) + drift * 30)), 2),
            "soil_temp_c": round(_diurnal(hour, 8 + 6 * season, 18 + 10 * season)
                                 + rng.gauss(0, 0.7) + drift * 20, 2),
            "ph": round(min(14.0, max(0.0, 6.4 + rng.gauss(0, 0.15) + drift * 4)), 2),
            "nitrogen_ppm": round(max(0.0, 42 + rng.gauss(0, 6) + drift * 60), 1),
            "phosphorus_ppm": round(max(0.0, 24 + rng.gauss(0, 4)), 1),
            "potassium_ppm": round(max(0.0, 160 + rng.gauss(0, 18)), 1),
            "ec_ds_m": round(max(0.0, 1.3 + rng.gauss(0, 0.2)), 3),
        }
    if device_type == "WEATHER_STATION":
        return {
            "air_temp_c": round(_diurnal(hour, 6 + 8 * season, 19 + 11 * season)
                                + rng.gauss(0, 1.0) + drift * 25, 2),
            "humidity_pct": round(max(0.0, min(100.0, 70 - 20 * math.sin((hour - 3) / 24 * 2 * math.pi)
                                               + rng.gauss(0, 5))), 1),
            "rainfall_mm": round(max(0.0, rng.expovariate(1 / 0.6) if rng.random() < 0.18 else 0.0), 2),
            "wind_speed_ms": round(max(0.0, abs(rng.gauss(3.5, 2.0))), 2),
            "solar_w_m2": round(max(0.0, 900 * max(0.0, math.sin((hour - 6) / 12 * math.pi))
                                    + rng.gauss(0, 30)), 1),
        }
    if device_type == "DRONE":
        return {
            "altitude_m": round(max(0.0, 85 + rng.gauss(0, 12) + drift * 400), 1),
            "battery_pct": round(max(0.0, min(100.0, 74 + rng.gauss(0, 9) - drift * 40)), 1),
            "images_captured": float(rng.randint(20, 240)),
            "speed_ms": round(max(0.0, 8.5 + rng.gauss(0, 1.6) + drift * 20), 2),
        }
    if device_type == "YIELD_MONITOR":
        return {
            "yield_t_ha": round(max(0.0, 9.2 + rng.gauss(0, 1.4) + drift * 20), 2),
            "moisture_pct": round(max(0.0, min(100.0, 17 + rng.gauss(0, 1.8) + drift * 40)), 2),
            "speed_kmh": round(max(0.0, 6.4 + rng.gauss(0, 1.0)), 2),
            "swath_m": round(max(0.0, 7.5 + rng.gauss(0, 0.2)), 2),
        }
    if device_type == "IRRIGATION_CONTROLLER":
        running = rng.random() < 0.35
        return {
            "flow_l_min": round(max(0.0, (420 + rng.gauss(0, 30)) if running else rng.uniform(0, 3)), 1),
            "pressure_bar": round(max(0.0, (3.2 + rng.gauss(0, 0.25)) if running
                                      else 0.4 + rng.gauss(0, 0.1)), 2),
            "duration_s": float(rng.randint(600, 3600) if running else 0),
        }
    if device_type == "COLD_CHAIN_SENSOR":
        return {
            "temp_c": round(2.8 + rng.gauss(0, 0.6) + drift * 25, 2),
            "humidity_pct": round(max(0.0, min(100.0, 85 + rng.gauss(0, 3))), 1),
            "shock_g": round(max(0.0, abs(rng.gauss(0.4, 0.5))), 2),
        }
    raise ValueError(f"Unknown device type {device_type}")


def telemetry_series(device_type: str, count: int, seed: int = 42,
                     interval_minutes: int = 15,
                     start: datetime | None = None) -> list[dict[str, Any]]:
    rng = random.Random(seed)
    start = start or datetime.now(timezone.utc) - timedelta(minutes=interval_minutes * count)
    series = []
    for i in range(count):
        when = start + timedelta(minutes=interval_minutes * i)
        series.append({"recorded_at": when.isoformat(),
                       "readings": telemetry_reading(device_type, when, rng)})
    return series


def anomalous_reading(device_type: str, seed: int = 7, mode: str = "spoof") -> dict[str, float]:
    """A reading an attacker or a failing sensor would produce."""
    rng = random.Random(seed)
    when = datetime.now(timezone.utc)
    if mode == "spoof":
        base = telemetry_reading(device_type, when, rng, drift=1.0)
    elif mode == "drift":
        base = telemetry_reading(device_type, when, rng, drift=0.55)
    elif mode == "stuck":
        base = {k: 0.0 for k in telemetry_reading(device_type, when, rng)}
    else:
        base = telemetry_reading(device_type, when, rng)
    return {k: round(v, 3) for k, v in base.items()}


